/**
 * R162（任务九）：插值补上了。原先这里明写"不做插值"，因为唯一会传占位符的是 tempera 图片池
 * 那个面板（宿主不渲染，看得见也点不到）；音乐人网格把「已加入 {{count}} 首…」这样的句子
 * 第一次送到了用户眼前，占位符就该换掉。只认 `{{参数名}}`，取不到参数原样留着（比吞掉好查）。
 * i18next 的复数形态 `_one` / `_other` 仍不做：本产品只有一档中文，量词本来就写在句子里。
 */
export const t = (key: string, options?: Record<string, unknown>): string => {
  const text = ZH[key] ?? key;
  if (!options) return text;
  return text.replace(/\{\{(\w+)\}\}/g, (unused, name: string) =>
    options[name] === undefined ? `{{${name}}}` : String(options[name]));
};

/** R52（第三期）：上游有文件只 import type { TFunction } from 'i18next'，shim 同形给出。 */
export type TFunction = (key: string, options?: Record<string, unknown>) => string;

const i18n = {
  t,
  language: "zh-CN",
  onChangeLanguage: () => {},
};

/** 与 react-i18next 同形的最小 hook：语言固定中文，无需订阅。 */
export function useTranslation(): { t: typeof t; i18n: typeof i18n } {
  useSyncExternalStore(
    () => () => {},
    () => "zh-CN",
  );
  return { t, i18n };
}

export default i18n;
